import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const packageDirectory = resolve(scriptDirectory, "..");
const workspaceDirectory = resolve(packageDirectory, "../..");
const outputPath = resolve(packageDirectory, "src/generated/receipt-brand-raster.ts");

const loadSharp = async () => {
  try {
    return (await import("sharp")).default;
  } catch {
    const pnpmDirectory = resolve(workspaceDirectory, "node_modules/.pnpm");
    const sharpDirectory = (await readdir(pnpmDirectory)).find((entry) =>
      entry.startsWith("sharp@")
    );
    if (!sharpDirectory) {
      throw new Error("Sharp wurde im pnpm-Store nicht gefunden.");
    }

    const modulePath = resolve(
      pnpmDirectory,
      sharpDirectory,
      "node_modules/sharp/lib/index.js"
    );
    return (await import(pathToFileURL(modulePath).href)).default;
  }
};

const sharp = await loadSharp();

const assets = [
  {
    exportName: "PIPA_RECEIPT_HEADER_BITMAP",
    fileName: "pipa-receipt-header.svg",
    alt: "Bistro PiPa mit Pizza-, Besteck- und Pasta-Symbolen"
  },
  {
    exportName: "PIPA_RECEIPT_FOOTER_BITMAP",
    fileName: "pipa-receipt-footer.svg",
    alt: "Standort Zionsgemeinde Haus Amos"
  },
  {
    exportName: "PIPA_RECEIPT_HEART_BITMAP",
    fileName: "pipa-receipt-heart.svg",
    alt: "Herz"
  }
];

const packRaster = ({ data, info }) => {
  const bytesPerRow = Math.ceil(info.width / 8);
  const packed = Buffer.alloc(bytesPerRow * info.height);

  for (let y = 0; y < info.height; y += 1) {
    for (let x = 0; x < info.width; x += 1) {
      const value = data[y * info.width + x];
      if (value < 128) {
        packed[y * bytesPerRow + Math.floor(x / 8)] |= 0x80 >> (x % 8);
      }
    }
  }

  return packed;
};

const generatedAssets = [];

for (const asset of assets) {
  const source = await readFile(resolve(packageDirectory, "assets", asset.fileName));
  const { data, info } = await sharp(source)
    .flatten({ background: "#ffffff" })
    .grayscale()
    .threshold(180)
    .raw()
    .toBuffer({ resolveWithObject: true });
  const packed = packRaster({ data, info });

  generatedAssets.push(
    `export const ${asset.exportName} = ${JSON.stringify(
      {
        width: info.width,
        height: info.height,
        dataBase64: packed.toString("base64"),
        alt: asset.alt
      },
      null,
      2
    )} as const;`
  );
}

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `// Generated by scripts/generate-receipt-brand.mjs. Do not edit manually.\n\n${generatedAssets.join(
    "\n\n"
  )}\n`,
  "utf8"
);

console.log(`Generated ${outputPath}`);
